import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const targets = [resolve(root, "dashboard/.env.local"), resolve(root, "worker/.env")];
if (targets.some(existsSync)) {
  console.error("Refusing to overwrite existing environment files. Move them privately first if switching to local Supabase.");
  process.exit(1);
}
const local = resolve(root, ".local");
mkdirSync(local, { recursive: true, mode: 0o700 });
const result = spawnSync(process.execPath, [resolve(root, "node_modules/supabase/dist/supabase.js"), "status", "-o", "json"], {
  cwd: root, env: { ...process.env, SUPABASE_HOME: resolve(local, "supabase-cli"), SUPABASE_TELEMETRY_DISABLED: "true", SUPABASE_USE_SLIM_IMAGES: "true" }, encoding: "utf8",
});
if (result.status !== 0) throw new Error("Local Supabase is unavailable. Run npm run db:start first.");
const status = JSON.parse(result.stdout);
const key = status.PUBLISHABLE_KEY || status.ANON_KEY;
if (!status.API_URL || !key || !status.DB_URL) throw new Error("Incomplete local Supabase status.");
if (!["localhost", "127.0.0.1"].includes(new URL(status.API_URL).hostname) ||
    !["localhost", "127.0.0.1"].includes(new URL(status.DB_URL).hostname)) throw new Error("Only local configuration can be generated by this helper.");
writeFileSync(targets[0], `SUPABASE_URL=${status.API_URL}\nSUPABASE_PUBLISHABLE_KEY=${key}\n`, { mode: 0o600, flag: "wx" });
writeFileSync(targets[1], `DATABASE_URL=${status.DB_URL}\nAUTOMATION_ENABLED=false\nDAILY_TARGET=30\nTIMEZONE=Asia/Karachi\n`, { mode: 0o600, flag: "wx" });
console.log("Created ignored dashboard/.env.local and worker/.env using local credentials. No hosted project was configured.");
